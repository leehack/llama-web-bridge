#!/usr/bin/env node
import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const sourceDir = resolve(root, 'js/src');
const outputDir = resolve(root, 'js');

const declarationSource = resolve(sourceDir, 'llama_webgpu_bridge.d.ts');
const declarationOutput = resolve(outputDir, 'llama_webgpu_bridge.d.ts');

const generatedBanner = (sourcePath) => (
  `// Generated by scripts/build_js_bridge.mjs from ${sourcePath}.\n`
  + '// Do not edit this file directly; update js/src/ and run npm run build:js.\n'
);

function restoreCoreImportHints(code, entry) {
  const source = ts.createSourceFile(entry, code, ts.ScriptTarget.ESNext);
  const imports = [];
  function visit(node) {
    if (ts.isCallExpression(node) && node.expression.kind === ts.SyntaxKind.ImportKeyword) {
      imports.push(node);
    }
    ts.forEachChild(node, visit);
  }
  visit(source);
  if (imports.length !== 1 || imports[0].arguments.length !== 1) {
    throw new Error(`${entry}: expected a single dynamic core import`);
  }
  // esbuild strips the hints when minifying whitespace. Keep consumer bundlers
  // from rewriting the runtime-selected core URL.
  const start = imports[0].arguments.pos;
  return code.slice(0, start) + '/* @vite-ignore */ /* webpackIgnore: true */ ' + code.slice(start);
}

await mkdir(outputDir, { recursive: true });

await Promise.all(['llama_webgpu_bridge.js', 'llama_webgpu_bridge_worker.js'].map(async (entry) => {
  const outfile = resolve(outputDir, entry);
  const { outputFiles: [bundle] } = await build({
    entryPoints: [resolve(sourceDir, entry)],
    outfile,
    write: false,
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: ['es2022'],
    minify: true,
    keepNames: true,
    sourcemap: false,
    legalComments: 'none',
    // Match tsconfig and Node's type stripping: keep every value import as written.
    tsconfigRaw: { compilerOptions: { verbatimModuleSyntax: true } },
    banner: { js: generatedBanner(`js/src/${entry}`).trimEnd() },
  });
  await writeFile(outfile, restoreCoreImportHints(bundle.text, entry), 'utf8');
}));
const declarationSourceText = await readFile(declarationSource, 'utf8');
await writeFile(
  declarationOutput,
  `${generatedBanner('js/src/llama_webgpu_bridge.d.ts')}${declarationSourceText}`,
  'utf8',
);
